#!/usr/bin/env python3
"""Publish BML editor declarations reflected by the SDL Player probe.

CKAngelScript's public reflection omits native @+ annotations. Restore those
from the registration declarations; all types, members and defaults come from
that runtime export. The existing CKAngelScript/ImGui sections are preserved.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import re

BEGIN = "// BEGIN BML+ REGISTERED API"
END = "// END BML+ REGISTERED API"


def cpp_strings(source: str):
    literal = r'"(?:\\.|[^"\\])*"'
    for group in re.finditer(rf'(?:{literal}\s*)+', source):
        yield "".join(ast.literal_eval(token[0]) for token in re.finditer(literal, group[0]))


def canonical(declaration: str) -> str:
    declaration = declaration.replace("BML::", "").replace("@+", "@")
    declaration = re.sub(r"\barray<([^<>]+)>", r"\1[]", declaration)
    return re.sub(r"\s+", "", declaration).rstrip(";")


def annotations(root: Path) -> dict[str, tuple[int, ...]]:
    found = {}
    for filename in ("AngelScriptBindings.cpp", "ScriptAuthorApi.cpp", "ScriptBehaviorBindings.inc"):
        source = root / "src/AngelScript" / filename
        if not source.exists():
            continue
        for declaration in cpp_strings(source.read_text(encoding="utf-8")):
            if "@+" not in declaration or "(" not in declaration:
                continue
            markers = tuple(index for index, match in enumerate(re.finditer("@", declaration))
                            if declaration[match.end():].startswith("+"))
            found[canonical(declaration)] = markers
    return found


def prepare(export: str, root: Path) -> str:
    restored = []
    auto_handles = annotations(root)
    for line in export.splitlines():
        indices = auto_handles.get(canonical(line))
        if indices:
            number = -1
            def annotate(match):
                nonlocal number
                number += 1
                return "@+" if number in indices else "@"
            line = re.sub("@", annotate, line)
        restored.append(line.rstrip())
    body = "\n".join(restored).strip() + "\n"
    # Refuse stale exports instead of silently publishing compatibility stubs.
    for obsolete in ("class InputHook", "class Logger", "interface Command {", "interface Timer {", "namespace Events {"):
        if obsolete in body:
            raise ValueError(f"Obsolete authoring declaration in runtime export: {obsolete}")
    compact = canonical(body)
    for required in ("int ReadMods(? &out mods) const", "int ReadCommands(? &out commands) const",
                     "int CheckDependencies(bool &out satisfied) const",
                     "Config@ Config() const", "Input@ Input() const"):
        if canonical(required) not in compact:
            raise ValueError(f"Missing registered declaration: {required}")
    return ("// Generated by tools/generate_script_api.py from the Player runtime export.\n"
            "// Native @+ ownership annotations are restored from BML registrations.\n"
            "// Editor reference only; do not include this file in a Mod.\n\n" + body)


def combine(current: str, api: str) -> str:
    if BEGIN in current:
        start = current.index(BEGIN)
        stop = current.index(END, start) + len(END)
    else:
        start = current.index("namespace BML {")
        stop = current.index("} // namespace BML", start) + len("} // namespace BML")
    current = current[:start] + BEGIN + "\n" + api.rstrip() + "\n" + END + current[stop:]
    current = current.replace("// Generated by tools/generate_as_predefined.py.",
                              "// CKAngelScript/ImGui editor baseline with the reflected BML+ API.")
    current = re.sub(r"^// Exported symbols:.*\n", "", current, flags=re.MULTILINE)
    return current


def publish(root: Path, export: Path, check: bool) -> None:
    api = prepare(export.read_text(encoding="utf-8"), root)
    path = root / "docs/api/bml-script-mod-api.as"
    combined = root / "docs/api/as.predefined"
    outputs = {path: api, combined: combine(combined.read_text(encoding="utf-8"), api)}
    for target, text in outputs.items():
        if check:
            if target.read_text(encoding="utf-8") != text:
                raise ValueError(f"Stale script declarations: {target}")
        else:
            target.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", type=Path, required=True,
                        help="bml-script-api.as written by RunPostProcessTest.py --dump-api")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        publish(args.root.resolve(), args.export.resolve(), args.check)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
